const fs = require('fs');
const path = require('path');

// CSV 파일 생성 함수
function createCSV(data, filename) {
  const csvContent = data.map(row => 
    row.map(cell => {
      // 셀에 쉼표나 줄바꿈이 있으면 큰따옴표로 감싸기
      const cellStr = String(cell || '');
      if (cellStr.includes(',') || cellStr.includes('\n') || cellStr.includes('"')) {
        return `"${cellStr.replace(/"/g, '""')}"`;
      }
      return cellStr;
    }).join(',')
  ).join('\n');
  
  const outputPath = path.join(__dirname, '..', 'docs', 'qa_csv', filename);
  fs.writeFileSync(outputPath, '\ufeff' + csvContent, 'utf8'); // UTF-8 BOM 추가
  console.log(`✅ CSV 파일 생성: ${filename}`);
}

